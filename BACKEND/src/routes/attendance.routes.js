const express = require("express");
const { z } = require("zod");
const { requireAuth } = require("../middlewares/auth.middleware");
const validate = require("../middlewares/validate.middleware");
const v = require("../validations/attendance.validation");
const c = require("../controllers/attendance.controller");
const router = express.Router();
const query = (req, res, next) => { const p = v.query.safeParse(req.query); if (!p.success) return res.status(400).json({ success: false, error: { code: "VALIDATION_ERROR", message: "Request validation failed", details: p.error.issues } }); req.validatedQuery = p.data; next(); };
const param = (name) => (req, res, next) => { const p = z.string().uuid().safeParse(req.params[name]); if (!p.success) return res.status(400).json({ success: false, error: { code: "VALIDATION_ERROR", message: `Invalid ${name}` } }); next(); };
router.use(requireAuth);
router.get("/school/roster", query, c.schoolRoster);
router.post("/school/mark", validate(v.schoolMark), c.schoolMark);
router.get("/school", query, c.schoolList);
router.get("/school/summary", query, c.schoolSummary);
router.get("/school/report", query, c.schoolReport);
router.get("/school/students/:studentId", param("studentId"), query, c.schoolHistory);
router.patch("/school/:attendanceId/correct", param("attendanceId"), validate(v.correction), c.schoolCorrection);
router.post("/college/sessions", validate(v.collegeSession), c.collegeCreateSession);
router.get("/college/sessions", query, c.collegeSessions);
router.get("/college/sessions/:sessionId", param("sessionId"), query, c.collegeSession);
router.get("/college/sessions/:sessionId/roster", param("sessionId"), query, c.collegeRoster);
router.post("/college/sessions/:sessionId/mark", param("sessionId"), validate(v.collegeMark), c.collegeMark);
router.get("/college", query, c.collegeList);
router.get("/college/summary", query, c.collegeSummary);
router.get("/college/report", query, c.collegeReport);
router.get("/college/students/:studentId", param("studentId"), query, c.collegeHistory);
router.patch("/college/:attendanceId/correct", param("attendanceId"), validate(v.correction), c.collegeCorrection);
module.exports = router;
